#!/usr/bin/env bash
# Run as root in a disposable Ubuntu VM with Docker and Git installed.
# Leaves the test installation running for the reboot check. Delete the VM afterwards.
set -euo pipefail

test "$(id -u)" = 0
test "$(ps -p 1 -o comm=)" = systemd

wait_for() {
  for ((attempt = 0; attempt < 90; attempt++)); do
    if "$@"; then return 0; fi
    sleep 1
  done
  journalctl -u "$unit" -n 30 --no-pager
  return 1
}

container_id() {
  docker ps -q --filter "label=com.docker.compose.project=$project" --filter label=com.docker.compose.service=api
}

responds() {
  local container
  container=$(container_id)
  test -n "$container" && test "$(docker exec "$container" wget -qO- http://127.0.0.1:8080 2>/dev/null)" = "$1"
}

if [[ ${1:-} = reboot-check ]]; then
  work=${2:?test directory}
  unit=$(cat "$work/unit")
  project=$(cat "$work/project")
  wait_for systemctl is-active --quiet "$unit"
  wait_for responds second
  test "$(container_id)" = "$(cat "$work/container")"
  test "$(cat /proc/sys/kernel/random/boot_id)" != "$(cat "$work/boot")"
  printf 'PASS: autostart after reboot, preserved container, HTTP response\n'
  exit
fi

binary=$(realpath "${1:?path to Linux composer binary}")
work=$(mktemp -d /var/tmp/composer-systemd.XXXXXXXX)
installation="systemd-check-$$"
unit="composer-$installation.service"
host="$work/host \$USER %n \"quoted\".yaml"
trap 'journalctl -u "$unit" -n 40 --no-pager' ERR

mkdir -p "$work/repo/apps/demo/api/vars" "$work/repo/apps/demo/api/configs"
git -C "$work/repo" init -q -b master
git -C "$work/repo" config user.email test@example.invalid
git -C "$work/repo" config user.name 'Composer systemd test'
cat > "$host" <<EOF
version: 1
installation: $installation
source:
  mode: local
  path: repo
  branches: {prod: master, stage: master}
  poll_interval: 1s
state_dir: state
docker:
  host: unix:///var/run/docker.sock
EOF
cat > "$work/repo/apps/demo/api/vars/base.yaml" <<'EOF'
message: first
compose:
  services:
    api:
      image: busybox:1.37.0
      command: [httpd, -f, -p, '8080', -h, /www]
      volumes: ['./configs/index.html:/www/index.html:ro']
      healthcheck:
        test: [CMD, wget, -qO-, 'http://127.0.0.1:8080']
        interval: 1s
        timeout: 1s
        retries: 5
EOF
printf '{{ .Vars.message }}\n' > "$work/repo/apps/demo/api/configs/index.html.tmpl"
git -C "$work/repo" add .
git -C "$work/repo" commit -qm first
docker pull busybox:1.37.0 >/dev/null

project=$("$binary" plan --config "$host" | python3 -c 'import json,sys; print(json.load(sys.stdin)["projects"][0]["name"])')
"$binary" install --config "$host"
systemctl is-enabled --quiet "$unit"
systemd-analyze verify "/etc/systemd/system/$unit"
wait_for responds first
first=$(container_id)
installed="/usr/local/lib/composer/$installation/composer"
cmp "$binary" "$installed"

# Reinstalling from the installed executable exercises atomic self replacement.
"$installed" install --config "$host"
wait_for responds first
test "$(container_id)" = "$first"

systemctl stop "$unit"
test "$(container_id)" = "$first"
responds first
systemctl start "$unit"
wait_for responds first
test "$(container_id)" = "$first"

# systemd must restart a crashed agent without recreating the app.
old_pid=$(systemctl show -p MainPID --value "$unit")
systemctl kill --signal=SIGKILL --kill-whom=main "$unit"
restarted() {
  local pid
  pid=$(systemctl show -p MainPID --value "$unit")
  test "$pid" != 0 && test "$pid" != "$old_pid" && systemctl is-active --quiet "$unit"
}
wait_for restarted
test "$(container_id)" = "$first"

sed -i 's/message: first/message: second/' "$work/repo/apps/demo/api/vars/base.yaml"
git -C "$work/repo" commit -qam second
wait_for responds second
test "$(container_id)" != "$first"

# An existing unit not generated by Composer must remain byte-for-byte unchanged.
other="/etc/systemd/system/composer-$installation-unmanaged.service"
printf '[Unit]\nDescription=Unmanaged sentinel\n' > "$other"
cp "$other" "$work/unmanaged.before"
sed "s/installation: $installation/installation: $installation-unmanaged/" "$host" > "$work/unmanaged.yaml"
if "$binary" install --config "$work/unmanaged.yaml"; then
  printf 'FAIL: replaced an unmanaged unit\n' >&2
  exit 1
fi
cmp "$other" "$work/unmanaged.before"
rm "$other"

printf '%s\n' "$unit" > "$work/unit"
printf '%s\n' "$project" > "$work/project"
container_id > "$work/container"
cat /proc/sys/kernel/random/boot_id > "$work/boot"
printf 'PASS: install, path escaping, reinstall, stop/start, crash restart, config rollout, unmanaged unit\n'
printf 'Reboot the VM, then run: bash %q reboot-check %q\n' "$0" "$work"
